#un tipo de dato describe el tipo de valor que contiene
#una variable, por ejemplo, un numero o un texto.
#los lenguajes de programacion usan tipos de datos

#ejemplos
name='Juan' #python knows this is a string
age_juan = 25 #python knows this is an integer

#nos enfocaremos en 4 tipos de datos
#entero: un numero sin decimales, por ejemplo, 10 o -5
my_integer_var = 10
print('integer: ', my_integer_var)#integer:10

#flotante: un numero con un punto decimal, como 4.41 o -0.4
my_float_var = 4.50
print('float:', my_float_var)#float: 4.50

#cadena: una secuancia de caracteres encerrados en comillas
#simples o dobles como 'hello world!'
my_string_var = 'hello'
print('string: ',my_string_var)

#booleano: Un tipo verdadero o falso, escrito como True o False

my_boolean_var = True
print('boolean: ', my_boolean_var)#boolean: True
